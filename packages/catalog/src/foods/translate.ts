function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function translateFoodName(en: string): string {
  let text = en.toLowerCase();
  for (const [re, es] of PHRASES) text = text.replace(re, es);
  const out = text
    .split(/(,\s*|\s+|\(|\))/)
    .map((token) => {
      const key = token.trim();
      if (!key || /^[,()\s]+$/.test(token)) return token;
      const clean = key.replace(/[^a-z0-9%/'".-]/g, '');
      return WORDS[clean] ?? token;
    })
    .join('');
  return capitalize(out.replace(/\s+/g, ' ').replace(/\s+,/g, ',').trim());
}

/** Traduce la etiqueta de una porción ("1 cup, chopped" → "1 taza, picado"). */
export function translatePortion(label: string): string {
  return translateFoodName(label).replace(/^./, (c) => c.toLowerCase());
}
